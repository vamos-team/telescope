-- 협업 캔버스 (#82). 설계와 결정 이유는 docs/backend/canvas.md

-- 캔버스. 소유자는 여기에만 두고 canvas_share에는 넣지 않는다. 삭제는 deleted_at으로 표시만 한다.
CREATE TABLE canvas (
    id             BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    name           VARCHAR(200) NOT NULL,
    quarter        VARCHAR(20)  NOT NULL,
    owner_id       BIGINT       NOT NULL,
    last_seq       BIGINT       NOT NULL DEFAULT 0,
    last_edited_by BIGINT       NULL,
    last_edited_at TIMESTAMP(6) NULL,
    deleted_at     TIMESTAMP(6) NULL,
    created_at     TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT fk_canvas_owner FOREIGN KEY (owner_id) REFERENCES users (id),
    CONSTRAINT fk_canvas_last_edited_by FOREIGN KEY (last_edited_by) REFERENCES users (id)
);
CREATE INDEX idx_canvas_owner ON canvas (owner_id);

-- 직접 초대한 사람별 권한 (EDIT / VIEW)
CREATE TABLE canvas_share (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    canvas_id  BIGINT       NOT NULL,
    user_id    BIGINT       NOT NULL,
    role       VARCHAR(10)  NOT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uk_canvas_share UNIQUE (canvas_id, user_id),
    CONSTRAINT fk_canvas_share_canvas FOREIGN KEY (canvas_id) REFERENCES canvas (id),
    CONSTRAINT fk_canvas_share_user FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX idx_canvas_share_user ON canvas_share (user_id);

-- 카드. ID는 화면이 만든 UUID. 위치와 두 글(프롬프트 카드 본문, 카드 프롬프트)을 다른 컬럼에 두고 글마다 버전을 둔다.
CREATE TABLE canvas_card (
    id             UUID             NOT NULL,
    canvas_id      BIGINT           NOT NULL,
    kind           VARCHAR(20)      NOT NULL,
    x              DOUBLE PRECISION NOT NULL DEFAULT 0,
    y              DOUBLE PRECISION NOT NULL DEFAULT 0,
    props          JSONB            NOT NULL DEFAULT '{}'::jsonb,
    text           TEXT             NULL,
    text_version   INT              NOT NULL DEFAULT 0,
    prompt         TEXT             NULL,
    prompt_version INT              NOT NULL DEFAULT 0,
    created_by     BIGINT           NOT NULL,
    created_at     TIMESTAMP(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT fk_canvas_card_canvas FOREIGN KEY (canvas_id) REFERENCES canvas (id),
    CONSTRAINT fk_canvas_card_creator FOREIGN KEY (created_by) REFERENCES users (id)
);
CREATE INDEX idx_canvas_card_canvas ON canvas_card (canvas_id);

-- 연결선. 양 끝 카드가 지워지면 같이 지운다. 선 프롬프트와 그 버전을 둔다.
CREATE TABLE canvas_link (
    id             UUID         NOT NULL,
    canvas_id      BIGINT       NOT NULL,
    source_card_id UUID         NOT NULL,
    target_card_id UUID         NOT NULL,
    rel            VARCHAR(10)  NOT NULL,
    prompt         TEXT         NULL,
    prompt_version INT          NOT NULL DEFAULT 0,
    created_by     BIGINT       NOT NULL,
    created_at     TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT fk_canvas_link_canvas FOREIGN KEY (canvas_id) REFERENCES canvas (id),
    CONSTRAINT fk_canvas_link_source FOREIGN KEY (source_card_id) REFERENCES canvas_card (id) ON DELETE CASCADE,
    CONSTRAINT fk_canvas_link_target FOREIGN KEY (target_card_id) REFERENCES canvas_card (id) ON DELETE CASCADE,
    CONSTRAINT fk_canvas_link_creator FOREIGN KEY (created_by) REFERENCES users (id)
);
CREATE INDEX idx_canvas_link_canvas ON canvas_link (canvas_id);

-- 계정 대응 확정(confirm_mapping) 결과. (캔버스, 개념, 회사)마다 마지막 결정 하나
CREATE TABLE canvas_mapping (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    canvas_id  BIGINT       NOT NULL,
    concept_id VARCHAR(100) NOT NULL,
    company    VARCHAR(50)  NOT NULL,
    cells      JSONB        NOT NULL DEFAULT '[]'::jsonb,
    accepted   BOOLEAN      NOT NULL,
    decided_by BIGINT       NOT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uk_canvas_mapping UNIQUE (canvas_id, concept_id, company),
    CONSTRAINT fk_canvas_mapping_canvas FOREIGN KEY (canvas_id) REFERENCES canvas (id),
    CONSTRAINT fk_canvas_mapping_user FOREIGN KEY (decided_by) REFERENCES users (id)
);

-- 이벤트 로그. 캔버스 단위로 seq가 1씩 늘어난다. 활동 로그도 여기서 만든다.
CREATE TABLE canvas_event (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    canvas_id  BIGINT       NOT NULL,
    seq        BIGINT       NOT NULL,
    request_id UUID         NOT NULL,
    author_id  BIGINT       NOT NULL,
    type       VARCHAR(40)  NOT NULL,
    payload    JSONB        NOT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uk_canvas_event_seq UNIQUE (canvas_id, seq),
    CONSTRAINT fk_canvas_event_canvas FOREIGN KEY (canvas_id) REFERENCES canvas (id),
    CONSTRAINT fk_canvas_event_author FOREIGN KEY (author_id) REFERENCES users (id)
);

-- 이벤트 묶음 요청. 같은 requestId 재전송에 처음 응답을 그대로 돌려주기 위해 둔다.
CREATE TABLE canvas_request (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    canvas_id  BIGINT       NOT NULL,
    request_id UUID         NOT NULL,
    author_id  BIGINT       NOT NULL,
    first_seq  BIGINT       NULL,
    last_seq   BIGINT       NOT NULL,
    response   JSONB        NOT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uk_canvas_request UNIQUE (canvas_id, request_id),
    CONSTRAINT fk_canvas_request_canvas FOREIGN KEY (canvas_id) REFERENCES canvas (id),
    CONSTRAINT fk_canvas_request_author FOREIGN KEY (author_id) REFERENCES users (id)
);
