-- 업로드 문서가 속한 캔버스. 문서 버전을 만들 때 한 번 넣고 바꾸지 않는다. 공용 문서는 비어 있다.
ALTER TABLE document_version ADD COLUMN canvas_id BIGINT NULL;
ALTER TABLE document_version
    ADD CONSTRAINT fk_document_version_canvas FOREIGN KEY (canvas_id) REFERENCES canvas (id);
CREATE INDEX idx_document_version_canvas ON document_version (canvas_id);

-- 자료 준비(파싱) 결과. 문서 버전은 만든 뒤 바꾸지 않으므로, 나중에 오는 결과는 따로 쌓는다.
-- ai 결과 형식이 확정 전(#109)이라 받은 JSON을 그대로 둔다. 문서 버전마다 하나.
CREATE TABLE document_preparation_result (
    id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    document_version_id BIGINT       NOT NULL,
    result              JSONB        NOT NULL,
    created_at          TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uk_document_preparation_result UNIQUE (document_version_id),
    CONSTRAINT fk_document_preparation_result_version FOREIGN KEY (document_version_id) REFERENCES document_version (id)
);
