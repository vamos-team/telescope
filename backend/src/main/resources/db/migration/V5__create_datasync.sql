CREATE TABLE data_sync_run (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    source      VARCHAR(100) NOT NULL,
    status      VARCHAR(20)  NOT NULL,
    started_at  TIMESTAMP(6)  NULL,
    finished_at TIMESTAMP(6)  NULL,
    created_at  TIMESTAMP(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id)
);
CREATE INDEX idx_data_sync_run_status ON data_sync_run (status);

CREATE TABLE data_version (
    id               BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    data_sync_run_id BIGINT      NOT NULL,
    is_active        BOOLEAN     NOT NULL,
    created_at       TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT fk_data_version_run FOREIGN KEY (data_sync_run_id) REFERENCES data_sync_run (id)
);
CREATE INDEX idx_data_version_active ON data_version (is_active);
CREATE INDEX idx_data_version_run ON data_version (data_sync_run_id);
